#!/usr/bin/env bash
# package-ps5x360e.sh - assemble the complete PS5X360E app folder, dist/PPSA50360.
#
# Copy the whole PPSA50360 folder to /data/homebrew/ on the PS5. It is its own app
# (title ID PPSA50360), so it installs beside PS5X360 (PPSA50011) without touching it.
# Both list the games in /data/homebrew/xbox360. Run after tools/build-canary-game.sh:
#     bash tools/package-ps5x360e.sh
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"
TITLE=PPSA50360
app="$root/dist/$TITLE"
eboot="${XBOX360PS5_OUTPUT_DIR:-$root/build/canary-game}/eboot.bin"
reference="$root/.deps/references/PS5_Vulkan"
[[ -f $eboot ]] || { echo "No eboot.bin at $eboot: build first" >&2; exit 2; }

# The C library companion every title carries (generated by PS5_Vulkan, GPL-3, verified).
libc="$reference/runtime/libc.prx"
if [[ ! -f $libc ]]; then
	( cd "$reference" && bash tools/rebuild-libc.sh )
fi
[[ $(sha256sum "$libc" | cut -c1-64) == e6ff45d16adf687855cc3b33b0c8a4132b6504360b221e0a34c7e99fb3ba0036 ]] ||
	{ echo "libc.prx does not match the published runtime" >&2; exit 2; }

# The game patch files PS5X360 0.6.0 ships (Xenia game-patches and its own), taken from
# its pinned release package; this fork's own patch files are copied over them.
upstream_zip="$root/.deps/ps5x360-0.6.0/PPSA50011.zip"
if [[ ! -f $upstream_zip ]]; then
	mkdir -p "$(dirname "$upstream_zip")"
	curl -fsSL -o "$upstream_zip.part" https://github.com/BrinooTk/PS5X360/releases/download/v0.6.0/PPSA50011.zip
	mv "$upstream_zip.part" "$upstream_zip"
fi
[[ $(sha256sum "$upstream_zip" | cut -c1-64) == b2bf7a7d242428cfa002ec557210dc885403580b58bda8d67a436a2550b67dd2 ]] ||
	{ echo "PS5X360 0.6.0 package does not match the pinned one" >&2; exit 2; }

rm -rf "$app.new"
mkdir -p "$app.new"/{sce_sys,sce_module,assets/roms,assets/patches,assets/game-configs,dlc,updates,licenses}
cp "$eboot" "$app.new/eboot.bin"
cp "$libc" "$app.new/sce_module/libc.prx"
for name in icon0.png pic0.png pic1.png; do cp "assets/branding/$name" "$app.new/sce_sys/$name"; done
version=$(head -n1 VERSION)
python3 - "$app.new/sce_sys/param.json" "$version" <<'PY'
import json, sys
path, version = sys.argv[1], sys.argv[2]
param = {
  "ageLevel": {"default": 0}, "applicationCategoryType": 0, "applicationDrmType": "free",
  "attribute": 0, "attribute2": 0, "attribute3": 0,
  "conceptId": "50360", "contentBadgeType": 1,
  "contentId": "UP9000-PPSA50360_00-PS5X360EDGE00001",
  "contentVersion": "00.001.000", "downloadDataSize": 256,
  "gameIntent": {"permittedIntents": [{"intentType": "launchActivity"}]},
  "localizedParameters": {"defaultLanguage": "en-US", "en-US": {"titleName": "PS5X360E"}},
  "masterVersion": "00.01",
  "pubtools": {"creationDate": "2026-10-12 00:00:00", "loudnessSnd0": "-28.00", "toolVersion": "2.00"},
  "requiredSystemSoftwareVersion": "0x0000000000000000", "sdkVersion": "0x0000000000000000",
  "titleId": "PPSA50360", "versionFileUri": ""}
open(path, "w").write(json.dumps(param, indent=2) + "\n")
PY
cp -r assets/fonts assets/sounds assets/kinect "$app.new/assets/"
cp assets/presets.txt "$app.new/assets/presets.txt"
unzip -q -o -j "$upstream_zip" 'PPSA50011/assets/patches/*' -d "$app.new/assets/patches"
cp assets/patches/*.patch.toml "$app.new/assets/patches/" 2>/dev/null || true
printf 'ps5_frame_interpolation=false\n' > "$app.new/framegen.conf"
cp licenses/* "$app.new/licenses/" 2>/dev/null || true
cp LICENSE "$app.new/LICENSE"
echo "$version" > "$app.new/VERSION"
cat > "$app.new/assets/roms/README.txt" <<'TXT'
Games are listed from /data/homebrew/xbox360 (shared with PS5X360), PS5X360's own
assets/roms folder, this folder, and xbox360 folders on USB drives. One folder per game:
an extracted game (default.xex and its data), an .iso image, or a GOD/STFS package.
No game, console BIOS or keys are included.
TXT
cat > "$app.new/updates/README.md" <<'TXT'
# Title updates

Copy an Xbox 360 title update package here (`PPSA50360/updates`), or into an `updates`
folder beside the game. Pressing Play installs the newest one that fits the game; the
game's sheet (Updates, with L1/R1) installs, turns on and turns off. One is active at a
time. Installed updates are kept in `saves/0000000000000000/<TITLE_ID>/000B0000`.
TXT
cat > "$app.new/dlc/README.md" <<'TXT'
# DLC

Copy Xbox 360 DLC packages here (`PPSA50360/dlc`), or into a `dlc` folder beside the
game. The game's sheet (DLCs, with L1/R1) installs, turns on and turns off; waiting DLC
is installed when you press Play.
TXT
cat > "$app.new/INSTALL.txt" <<TXT
PS5X360E $version - an experimental fork of PS5X360 on Xenia Edge.

Copy this PPSA50360 folder to /data/homebrew/ on the PS5. It is a separate app from
PS5X360 (PPSA50011): its own settings, saves, caches and logs (in PPSA50360). Both list
the games in /data/homebrew/xbox360.

No game, console BIOS or keys are included. Use only games you own.
TXT
rm -rf "$app"
mv "$app.new" "$app"
echo "PS5X360E $version app folder: $app ($(du -sh "$app" | cut -f1))"
